def first_line(text: str) -> str:
    return text.splitlines()[0] if text else ""


def leaf_text(item: tuple[str, str, str]) -> str:
    name, isa, shot = item
    return f"{name}\nis-a {isa}\n🎬 {shot}"


def text_successors(node_id: str, node_by_id: dict[str, dict[str, Any]], edges: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for edge in edges:
        if edge.get("fromNode") != node_id:
            continue
        target = node_by_id.get(str(edge.get("toNode")))
        if target and target.get("type") == "text":
            out.append(target)
    return out


def find_column_leaves(header: dict[str, Any], node_by_id: dict[str, dict[str, Any]], edges: list[dict[str, Any]]) -> list[dict[str, Any]]:
    leaves: list[dict[str, Any]] = []
    current = header
    column_x = current.get("x")
    for _ in range(5):
        candidates = [
            node for node in text_successors(str(current["id"]), node_by_id, edges)
            if node.get("x") == column_x and node.get("y", -10**9) > current.get("y", -10**9)
        ]
        if not candidates:
            raise ValueError(f"无法沿场景列继续：{header['id']} -> {current['id']}")
        current = min(candidates, key=lambda node: node.get("y", 0))
        leaves.append(current)
    return leaves


def rewrite_canvas(path: Path, style: str, categories: list[dict[str, Any]]) -> tuple[bool, list[str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    nodes: list[dict[str, Any]] = data.get("nodes", [])
    edges: list[dict[str, Any]] = data.get("edges", [])
    node_by_id = {str(node.get("id")): node for node in nodes}

    scene_headers = [
        node for node in nodes
        if node.get("type") == "text" and str(node.get("text", "")).startswith("🌄 场景 is-a")
    ]
    if len(scene_headers) != 1:
        raise ValueError(f"{path}: 场景总标题数量应为 1，实际 {len(scene_headers)}")
    scene_header = scene_headers[0]

    category_headers = text_successors(str(scene_header["id"]), node_by_id, edges)
    category_headers = sorted(category_headers, key=lambda node: node.get("x", 0))
    if len(category_headers) != 3:
        raise ValueError(f"{path}: 场景分类应为 3 列，实际 {len(category_headers)}")

    columns: list[list[dict[str, Any]]] = []
    for header in category_headers:
        columns.append(find_column_leaves(header, node_by_id, edges))

    old_names = [first_line(node.get("text", "")) for col in columns for node in col]
    new_names = [item[0] for cat in categories for item in cat["items"]]
    already_fixed = old_names == new_names
    if already_fixed:
        return False, new_names

    scene_header["text"] = (
        f"🌄 场景 is-a {style}可绘制场景类目 "
        f"├ {categories[0]['title']} ┤ {categories[1]['title']} ┤ {categories[2]['title']} "
        "├ ↔ 服装·建筑·构件·元素"
    )

    for header, leaves, category in zip(category_headers, columns, categories):
        header["text"] = f"{category['title']}\n{category['subtitle']}"
        if len(category["items"]) != 5:
            raise ValueError(f"{style}/{category['title']}: 叶子数量不是 5")
        for node, item in zip(leaves, category["items"]):
            node["text"] = leaf_text(item)

    # 保持节点、边和其他字段原顺序；仅统一 JSON 缩进。
    path.write_text(json.dumps(data, ensure_ascii=False, indent="\t") + "\n", encoding="utf-8")
    return True, new_names


def main() -> int:
    if not ROOT.exists():
        print(f"ERROR: 目录不存在：{ROOT}", file=sys.stderr)
        return 2

    canvas_paths = sorted(
        path for path in ROOT.glob(f"*{SUFFIX}")
        if ".bak" not in path.name and ".backup" not in path.name
    )
    found_styles = {path.name[: -len(SUFFIX)] for path in canvas_paths}
    expected_styles = set(SCENE_LIBRARY)

    missing_files = sorted(expected_styles - found_styles)
    unmapped_files = sorted(found_styles - expected_styles)
    if missing_files or unmapped_files:
        print(f"ERROR: 缺少 Canvas：{missing_files}", file=sys.stderr)
        print(f"ERROR: 未映射 Canvas：{unmapped_files}", file=sys.stderr)
        return 3

    changed: list[tuple[str, list[str]]] = []
    unchanged: list[str] = []
    errors: list[str] = []

    for path in canvas_paths:
        style = path.name[: -len(SUFFIX)]
        try:
            did_change, names = rewrite_canvas(path, style, SCENE_LIBRARY[style])
            if did_change:
                changed.append((style, names))
            else:
                unchanged.append(style)
        except Exception as exc:  # noqa: BLE001
            errors.append(f"{style}: {exc}")

    if errors:
        print("ERROR: 场景区修复失败：", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        return 4

    report: list[str] = [
        "# 概念库场景区全库修复报告",
        "",
        "## 结果",
        "",
        f"- 扫描 Canvas：{len(canvas_paths)}",
        f"- 本次改写：{len(changed)}",
        f"- 已符合新结构：{len(unchanged)}",
        "- 修改范围：仅场景总标题、3 个分类标题、15 个场景叶子文本",
        "- 保留范围：服装、建筑、构件、元素、file 节点、参考图节点、全部既有边",
        "",
        "## 新场景概念",
        "",
    ]
    for style, names in changed:
        report.append(f"### {style}")
        report.append("")
        for index, name in enumerate(names, start=1):
            report.append(f"{index}. {name}")
        report.append("")
    if unchanged:
        report.extend(["## 未重复改写", "", "、".join(unchanged), ""])

    REPORT_PATH.write_text("\n".join(report), encoding="utf-8")
    print(f"OK: scanned={len(canvas_paths)} changed={len(changed)} unchanged={len(unchanged)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
